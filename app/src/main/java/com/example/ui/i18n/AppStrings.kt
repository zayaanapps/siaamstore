fun String.toBengaliDigits(language: AppLanguage): String {
    if (language != AppLanguage.BENGALI) return this
    val map = charArrayOf('০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯')
    val sb = StringBuilder(length)
    for (c in this) {
        if (c in '0'..'9') {
            sb.append(map[c - '0'])
        } else {
            sb.append(c)
        }
    }
    return sb.toString()
}
